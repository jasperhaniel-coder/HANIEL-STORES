-- =====================================================================
-- HANIEL STORES - PHASE 1: DATABASE SCHEMA
-- ---------------------------------------------------------------------
-- HOW TO RUN: Supabase dashboard -> SQL Editor -> New query -> paste
-- this whole file -> Run. Then do the same with seed.sql.
--
-- Safe to run more than once: it only creates what is missing and
-- replaces policies/triggers/functions with the latest version.
-- Everything runs in ONE transaction: if anything fails, nothing is
-- applied, so you can fix the problem and simply run it again.
--
-- BUILT TO GROW:
--  * categories live in their own table (add a category = add a row)
--  * indexes for category filter, price sort and name search, so the
--    shop stays fast with thousands of products
--  * home-page sections use flags (is_flash_sale / is_best_selling)
--    instead of "first 5 products", so new products never push the
--    wrong items into those sections
--  * products are hidden with is_active = false instead of deleted,
--    and order_items keep a snapshot of name/price/image, so old
--    orders never break when a product changes or disappears
--  * every id is generated by the database - nothing is hardcoded
-- =====================================================================

begin;

create extension if not exists pg_trgm with schema extensions;

-- ---------------------------------------------------------------------
-- 1. SMALL HELPER FUNCTIONS
-- ---------------------------------------------------------------------

-- Keeps updated_at current on any table that has it.
create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

-- "Women's Fashion" -> "womens-fashion"
create or replace function public.make_slug(input text)
returns text
language sql
immutable
set search_path = ''
as $$
  select coalesce(
    nullif(
      trim(both '-' from regexp_replace(
        lower(replace(replace(coalesce(input, ''), '''', ''), '’', '')),
        '[^a-z0-9]+', '-', 'g')),
      ''),
    'item'
  );
$$;

-- ---------------------------------------------------------------------
-- 2. CATEGORIES
-- ---------------------------------------------------------------------
create table if not exists public.categories (
  id          bigint generated by default as identity primary key,
  name        text not null unique check (char_length(trim(name)) > 0),
  slug        text not null unique,
  sort_order  integer not null default 0,
  is_active   boolean not null default true,
  created_at  timestamptz not null default now()
);

create or replace function public.categories_set_slug()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if new.slug is null or trim(new.slug) = '' then
    new.slug := public.make_slug(new.name);
  else
    new.slug := public.make_slug(new.slug);
  end if;
  return new;
end;
$$;

drop trigger if exists categories_slug on public.categories;
create trigger categories_slug
  before insert on public.categories
  for each row execute function public.categories_set_slug();

-- ---------------------------------------------------------------------
-- 3. PRODUCTS
-- ---------------------------------------------------------------------
create table if not exists public.products (
  id                bigint generated by default as identity primary key,
  slug              text not null unique,
  name              text not null check (char_length(trim(name)) > 0),
  description       text,
  category_id       bigint not null references public.categories(id) on delete restrict,

  -- numeric(12,2) is exact (no floating-point rounding errors with money)
  price             numeric(12,2) not null check (price >= 0),
  old_price         numeric(12,2) check (old_price is null or old_price >= 0),
  discount_percent  smallint check (discount_percent is null or discount_percent between 1 and 100),

  rating            numeric(2,1) not null default 0 check (rating between 0 and 5),
  reviews_count     integer not null default 0 check (reviews_count >= 0),

  image_url         text not null default 'https://placehold.co/600x600/f5f5f5/777?text=Product',
  gallery           text[] not null default '{}',

  -- Inventory is optional. While track_inventory is false the product is
  -- always available (this matches how your site works today).
  track_inventory   boolean not null default false,
  stock_quantity    integer not null default 0 check (stock_quantity >= 0),

  is_active         boolean not null default true,
  is_flash_sale     boolean not null default false,
  is_best_selling   boolean not null default false,

  created_at        timestamptz not null default now(),
  updated_at        timestamptz not null default now()
);

create index if not exists products_category_idx   on public.products (category_id) where is_active;
create index if not exists products_price_idx      on public.products (price)       where is_active;
create index if not exists products_flash_idx      on public.products (id)          where is_active and is_flash_sale;
create index if not exists products_best_idx       on public.products (id)          where is_active and is_best_selling;
create index if not exists products_name_trgm_idx  on public.products using gin (name extensions.gin_trgm_ops);

-- When you add a product without a slug, one is generated from its name.
create or replace function public.products_set_slug()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  base text;
begin
  if new.slug is null or trim(new.slug) = '' then
    base := public.make_slug(new.name);
    if exists (select 1 from public.products p where p.slug = base and p.id <> new.id) then
      base := base || '-' || new.id::text;
    end if;
    new.slug := base;
  else
    new.slug := public.make_slug(new.slug);
  end if;
  return new;
end;
$$;

drop trigger if exists products_slug on public.products;
create trigger products_slug
  before insert on public.products
  for each row execute function public.products_set_slug();

drop trigger if exists products_updated_at on public.products;
create trigger products_updated_at
  before update on public.products
  for each row execute function public.set_updated_at();

-- ---------------------------------------------------------------------
-- 4. PROFILES (one row per signed-up user, linked to Supabase Auth)
-- ---------------------------------------------------------------------
create table if not exists public.profiles (
  id          uuid primary key references auth.users(id) on delete cascade,
  full_name   text,
  phone       text,
  role        text not null default 'customer' check (role in ('customer', 'admin')),
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

drop trigger if exists profiles_updated_at on public.profiles;
create trigger profiles_updated_at
  before update on public.profiles
  for each row execute function public.set_updated_at();

-- Is the person making this request an admin? Used by the policies below.
-- SECURITY DEFINER lets it read profiles without triggering policy loops.
create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.profiles
    where id = (select auth.uid()) and role = 'admin'
  );
$$;

-- Automatically create a profile whenever someone signs up.
-- The signup form will send the name as user metadata ("full_name").
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, full_name, phone)
  values (
    new.id,
    nullif(trim(coalesce(new.raw_user_meta_data ->> 'full_name', '')), ''),
    nullif(new.phone, '')
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

