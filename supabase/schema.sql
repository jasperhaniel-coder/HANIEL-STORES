-- ---------------------------------------------------------------------
-- 6. COUPONS (replaces the codes that were visible in cart.js)
-- ---------------------------------------------------------------------
create table if not exists public.coupons (
  code         text primary key check (code = upper(code) and char_length(code) between 3 and 40),
  percent_off  smallint not null check (percent_off between 1 and 100),
  min_order    numeric(12,2) not null default 0 check (min_order >= 0),
  max_uses     integer check (max_uses is null or max_uses > 0),
  used_count   integer not null default 0 check (used_count >= 0),
  starts_at    timestamptz,
  expires_at   timestamptz,
  is_active    boolean not null default true,
  created_at   timestamptz not null default now()
);

-- ---------------------------------------------------------------------
-- 7. ORDERS
-- ---------------------------------------------------------------------
create table if not exists public.orders (
  id               uuid primary key default gen_random_uuid(),
  -- Friendly number customers see and quote: HS-100001, HS-100002, ...
  order_number     bigint generated always as identity (start with 100001) unique,
  user_id          uuid references auth.users(id) on delete set null,
  customer_email   text not null,

  -- status = where the parcel is; payment_status = has the money arrived
  status           text not null default 'pending'
                     check (status in ('pending', 'processing', 'shipped', 'delivered', 'cancelled')),
  payment_status   text not null default 'pending'
                     check (payment_status in ('pending', 'paid', 'failed', 'refunded')),

  currency         text not null default 'NGN' check (char_length(currency) = 3),
  subtotal         numeric(12,2) not null check (subtotal >= 0),
  discount_amount  numeric(12,2) not null default 0 check (discount_amount >= 0),
  shipping_fee     numeric(12,2) not null default 0 check (shipping_fee >= 0),
  total            numeric(12,2) not null check (total >= 0),
  coupon_code      text references public.coupons(code) on update cascade on delete set null,

  shipping_name     text not null,
  shipping_phone    text not null,
  shipping_address  text not null,
  shipping_city     text not null,
  shipping_state    text not null,
  shipping_notes    text,

  payment_reference text unique,      -- the Paystack reference
  paid_at           timestamptz,
  tracking_number   text,

  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now(),

  -- The database itself refuses an order whose maths does not add up.
  constraint orders_total_matches check (total = subtotal - discount_amount + shipping_fee)
);

create index if not exists orders_user_idx    on public.orders (user_id, created_at desc);
create index if not exists orders_status_idx  on public.orders (status, created_at desc);

drop trigger if exists orders_updated_at on public.orders;
create trigger orders_updated_at
  before update on public.orders
  for each row execute function public.set_updated_at();

create table if not exists public.order_items (
  id            bigint generated by default as identity primary key,
  order_id      uuid not null references public.orders(id) on delete cascade,
  -- If a product is ever deleted, the order keeps its name/price/image below.
  product_id    bigint references public.products(id) on delete set null,
  product_name  text not null,
  image_url     text,
  unit_price    numeric(12,2) not null check (unit_price >= 0),
  quantity      integer not null check (quantity between 1 and 99),
  line_total    numeric(12,2) generated always as (unit_price * quantity) stored
);

create index if not exists order_items_order_idx on public.order_items (order_id);

-- Timeline shown on the Track Order page.
create table if not exists public.order_events (
  id          bigint generated by default as identity primary key,
  order_id    uuid not null references public.orders(id) on delete cascade,
  status      text not null,
  note        text,
  created_at  timestamptz not null default now()
);

create index if not exists order_events_order_idx on public.order_events (order_id, created_at);

-- Writes a timeline entry when an order is created or its status changes.
create or replace function public.log_order_status()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if tg_op = 'INSERT' then
    insert into public.order_events (order_id, status) values (new.id, new.status);
  elsif new.status is distinct from old.status then
    insert into public.order_events (order_id, status) values (new.id, new.status);
  end if;
  return new;
end;
$$;

drop trigger if exists orders_log_status on public.orders;
create trigger orders_log_status
  after insert or update of status on public.orders
  for each row execute function public.log_order_status();

