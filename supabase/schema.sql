create table if not exists public.contact_messages (
  id          bigint generated by default as identity primary key,
  name        text not null check (char_length(trim(name)) between 2 and 100),
  email       text not null check (email ~* '^[^\s@]+@[^\s@]+\.[^\s@]+$' and char_length(email) <= 254),
  phone       text not null check (char_length(phone) between 7 and 20),
  message     text not null check (char_length(trim(message)) between 10 and 5000),
  status      text not null default 'new' check (status in ('new', 'read', 'replied')),
  created_at  timestamptz not null default now()
);

create table if not exists public.newsletter_subscribers (
  id          bigint generated by default as identity primary key,
  email       text not null check (email ~* '^[^\s@]+@[^\s@]+\.[^\s@]+$' and char_length(email) <= 254),
  is_active   boolean not null default true,
  created_at  timestamptz not null default now()
);

-- Same email in different letter-case counts as the same subscriber.
create unique index if not exists newsletter_email_unique
  on public.newsletter_subscribers (lower(email));

-- ---------------------------------------------------------------------
-- 8b. CATEGORY COUNTS (used by the category filter on products.html)
-- Lists each active category with how many active products it holds, so
-- the filter can hide empty categories without scanning every product.
-- security_invoker = the view obeys the same row-level security as the
-- person asking, so hidden products are never counted.
-- ---------------------------------------------------------------------
create or replace view public.category_counts
with (security_invoker = true) as
select c.id, c.name, c.slug, c.sort_order, count(p.id)::int as product_count
from public.categories c
left join public.products p on p.category_id = c.id and p.is_active
where c.is_active
group by c.id;

-- ---------------------------------------------------------------------
-- 9. ROW LEVEL SECURITY
-- With RLS on and no matching policy, a request is DENIED. Our own
-- server code (/api, using the service_role key) bypasses RLS, so it
-- can create orders, record payments, and so on. Browsers only ever
-- get the narrow access spelled out below.
-- ---------------------------------------------------------------------
alter table public.categories             enable row level security;
alter table public.products               enable row level security;
alter table public.profiles               enable row level security;
alter table public.cart_items             enable row level security;
alter table public.wishlist_items         enable row level security;
alter table public.coupons                enable row level security;
alter table public.orders                 enable row level security;
alter table public.order_items            enable row level security;
alter table public.order_events           enable row level security;
alter table public.contact_messages       enable row level security;
alter table public.newsletter_subscribers enable row level security;

-- Categories and products: everyone can read active ones; admins manage.
drop policy if exists categories_public_read on public.categories;
create policy categories_public_read on public.categories
  for select to anon, authenticated using (is_active);

drop policy if exists categories_admin_all on public.categories;
create policy categories_admin_all on public.categories
  for all to authenticated using (public.is_admin()) with check (public.is_admin());

drop policy if exists products_public_read on public.products;
create policy products_public_read on public.products
  for select to anon, authenticated using (is_active);

drop policy if exists products_admin_all on public.products;
create policy products_admin_all on public.products
  for all to authenticated using (public.is_admin()) with check (public.is_admin());

-- Profiles: you can read and edit your own (name/phone only - see grants);
-- admins can read everyone's.
drop policy if exists profiles_select on public.profiles;
create policy profiles_select on public.profiles
  for select to authenticated
  using (id = (select auth.uid()) or public.is_admin());

drop policy if exists profiles_update_own on public.profiles;
create policy profiles_update_own on public.profiles
  for update to authenticated
  using (id = (select auth.uid()))
  with check (id = (select auth.uid()));

-- Cart and wishlist: only your own rows.
drop policy if exists cart_own_all on public.cart_items;
create policy cart_own_all on public.cart_items
  for all to authenticated
  using (user_id = (select auth.uid()))
  with check (user_id = (select auth.uid()));

drop policy if exists wishlist_own_all on public.wishlist_items;
create policy wishlist_own_all on public.wishlist_items
  for all to authenticated
  using (user_id = (select auth.uid()))
  with check (user_id = (select auth.uid()));

-- Orders: customers can only READ their own. Creating and paying for
-- orders happens on the server. Admins can read and update all.
drop policy if exists orders_select on public.orders;
create policy orders_select on public.orders
  for select to authenticated
  using (user_id = (select auth.uid()) or public.is_admin());

drop policy if exists orders_admin_update on public.orders;
create policy orders_admin_update on public.orders
  for update to authenticated
  using (public.is_admin()) with check (public.is_admin());

drop policy if exists order_items_select on public.order_items;
create policy order_items_select on public.order_items
  for select to authenticated
  using (exists (
    select 1 from public.orders o
    where o.id = order_items.order_id
      and (o.user_id = (select auth.uid()) or public.is_admin())
  ));

drop policy if exists order_events_select on public.order_events;
create policy order_events_select on public.order_events
  for select to authenticated
  using (exists (
    select 1 from public.orders o
    where o.id = order_events.order_id
      and (o.user_id = (select auth.uid()) or public.is_admin())
  ));

-- Coupons, contact messages, subscribers: admins only. Visitors submit
-- forms through /api (which validates and rate-limits them), never
-- straight to these tables.
drop policy if exists coupons_admin_all on public.coupons;
create policy coupons_admin_all on public.coupons
  for all to authenticated using (public.is_admin()) with check (public.is_admin());

drop policy if exists contact_admin_all on public.contact_messages;
create policy contact_admin_all on public.contact_messages
  for all to authenticated using (public.is_admin()) with check (public.is_admin());

drop policy if exists newsletter_admin_all on public.newsletter_subscribers;
create policy newsletter_admin_all on public.newsletter_subscribers
  for all to authenticated using (public.is_admin()) with check (public.is_admin());

-- ---------------------------------------------------------------------
-- 10. PERMISSIONS (least privilege)
-- Start from nothing for browser roles, then grant only what is needed.
-- RLS above still decides WHICH rows each person may touch.
-- ---------------------------------------------------------------------
revoke all on all tables in schema public from anon, authenticated;

grant usage on schema public to anon, authenticated, service_role;

grant select on public.categories, public.products, public.category_counts to anon, authenticated;
grant insert, update, delete on public.categories, public.products to authenticated;     -- admins only (RLS)

grant select on public.profiles to authenticated;
grant update (full_name, phone) on public.profiles to authenticated;                     -- NOT role

grant select, insert, update, delete on public.cart_items to authenticated;
grant select, insert, delete on public.wishlist_items to authenticated;

grant select on public.orders, public.order_items, public.order_events to authenticated;
grant update on public.orders to authenticated;                                          -- admins only (RLS)

grant select, insert, update, delete
  on public.coupons, public.contact_messages, public.newsletter_subscribers
  to authenticated;                                                                      -- admins only (RLS)

grant all on all tables in schema public to service_role;
grant all on all sequences in schema public to service_role;

-- Internal functions should not be callable from the browser.
revoke all on function public.handle_new_user()  from public, anon, authenticated;
revoke all on function public.log_order_status() from public, anon, authenticated;
revoke all on function public.is_admin()         from public, anon;
grant execute on function public.is_admin()      to authenticated, service_role;

commit;

